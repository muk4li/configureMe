import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";
import path from "node:path";
import JSZip from "jszip";

const bundleFiles = [
  "bootstrap.ps1",
  "config/catalog.json",
  "config/windows-server-2022-developer.json",
  "modules/Detection.psm1",
  "modules/Downloads.psm1",
  "modules/GuiWorker.psm1",
  "modules/Installation.psm1",
  "modules/Logging.psm1",
  "modules/Verification.psm1",
  "assets/firefox-bookmarks.html",
  "README.md",
  "SECURITY.md",
] as const;

export async function createServer2022Bundle(packages: string[]): Promise<Buffer> {
  const directory = path.join(process.cwd(), "bootstrap", "windows-server-2022-developer");
  const zip = new JSZip();
  const files = [];
  let bootstrapVersion: string | undefined;
  for (const file of [...bundleFiles].sort()) {
    let contents = await readFile(path.join(directory, file));
    if (file === "bootstrap.ps1") {
      bootstrapVersion = contents.toString("utf8").match(/\$bootstrapVersion\s*=\s*"([^"]+)"/)?.[1];
    }
    if (file === "config/windows-server-2022-developer.json") {
      const profile = JSON.parse(contents.toString("utf8"));
      profile.packages = packages;
      contents = Buffer.from(`${JSON.stringify(profile, null, 2)}\n`);
    }
    files.push({ path: file, sha256: createHash("sha256").update(contents).digest("hex"), sizeBytes: contents.length });
    zip.file(`configureMe-QuickSetup/${file}`, contents, { date: new Date("1980-01-01T00:00:00Z"), createFolders: false });
  }
  if (!bootstrapVersion) throw new Error("The bundled bootstrap version is missing.");
  const sourceCommit = process.env.CONFIGUREME_SOURCE_COMMIT;
  const manifest = {
    schemaVersion: 1,
    packageName: "configureMe-WindowsServer2022-Developer-QuickSetup",
    bootstrapVersion,
    sourceCommitSha: sourceCommit && /^[a-f0-9]{40,64}$/i.test(sourceCommit) ? sourceCommit.toLowerCase() : null,
    provenance: "Generated by the web portal; unsigned. Source commit is supplied by the deployment when available.",
    files,
  };
  zip.file("configureMe-QuickSetup/manifest.json", `${JSON.stringify(manifest, null, 2)}\n`, { date: new Date("1980-01-01T00:00:00Z"), createFolders: false });
  return zip.generateAsync({ type: "nodebuffer", compression: "DEFLATE", compressionOptions: { level: 6 }, platform: "DOS" });
}
